%% build_SITRA_S2.m
% S2 - Traffic demand + four-branch queue plant inside SITRA_Traffic_Hardware.slx
%
% Fills 01_Traffic_Demand and 02_Traffic_Queue_Plant created by build_SITRA_S1.
% Equations are copied from the frozen Part 8 loop (same order of updates):
%   dep(b)  = min(cap(b), q(b)/dt)  for b == active (B1..B3), else 0
%   arr(4)  = dep(active);  dep(4) = min(cap(4), q(4)/dt)
%   qNext   = max(0, q + dt*(arr-dep));  res = arr-dep-(qNext-q)/dt
%
% Run from the project root (needs build_SITRA_S1.m there). Then run test_SITRA_S2.

modelName = 'SITRA_Traffic_Hardware';
if ~exist([modelName '.slx'],'file')
    build_SITRA_S1;          % S1 clears the workspace, so nothing is defined above
end
modelName = 'SITRA_Traffic_Hardware';
load_system(modelName);

demandCode = sprintf([ ...
 'function d = demandProfile(t)\n' ...
 '%% Normal / surge demand [B1 B2 B3] veh/s (matches Part 8)\n' ...
 'normalD = [0.10 0.07 0.05];\n' ...
 'surgeD  = [0.30 0.07 0.05];\n' ...
 'if t >= 200 && t < 400\n' ...
 '    d = surgeD;\n' ...
 'else\n' ...
 '    d = normalD;\n' ...
 'end\n' ...
 'end\n']);


queueCode = sprintf([ ...
 'function [qNext, res] = queueStep(q, demand, active)\n' ...
 '%% One 1-s update of the 4-branch queue network\n' ...
 'q = reshape(q,1,4);\n' ...
 'demand = reshape(demand,1,3);\n' ...
 'cap = [0.65 0.35 0.25 0.45];\n' ...
 'dt = 1;\n' ...
 'arr = [demand 0];\n' ...
 'dep = zeros(1,4);\n' ...
 'a = round(active);\n' ...
 'if a >= 1 && a <= 3\n' ...
 '    dep(a) = min(cap(a), q(a)/dt);\n' ...
 '    arr(4) = dep(a);\n' ...
 'end\n' ...
 'dep(4) = min(cap(4), q(4)/dt);\n' ...
 'qNext = max(zeros(1,4), q + dt*(arr-dep));\n' ...
 'res = arr-dep-(qNext-q)/dt;\n' ...
 'end\n']);



%% ---------- 01_Traffic_Demand ----------
s1 = [modelName '/01_Traffic_Demand'];
clearSubsystem(s1);
add_block('simulink/Sources/Digital Clock',[s1 '/Clock'], ...
    'SampleTime','1','Position',[80 60 140 90]);
addMatlabFunction(s1,'DemandFcn',demandCode,[200 50 340 110]);
add_block('simulink/Sinks/To Workspace',[s1 '/LogDemand'], ...
    'VariableName','s2_demand','SaveFormat','Array','SampleTime','1', ...
    'MaxDataPoints','inf','Position',[430 140 520 170]);
add_line(s1,'Clock/1','DemandFcn/1');
add_line(s1,'DemandFcn/1','Out1/1');
add_line(s1,'DemandFcn/1','LogDemand/1');
set_param([s1 '/Out1'],'Position',[430 60 460 75]);

%% ---------- 02_Traffic_Queue_Plant ----------
s2 = [modelName '/02_Traffic_Queue_Plant'];
clearSubsystem(s2);
addMatlabFunction(s2,'QueueStep',queueCode,[200 50 360 140]);
add_block('simulink/Discrete/Unit Delay',[s2 '/Qstate'], ...
    'InitialCondition','zeros(1,4)','SampleTime','1', ...
    'Position',[260 200 320 240],'Orientation','left');
add_block('simulink/Sinks/To Workspace',[s2 '/LogQ'], ...
    'VariableName','s2_q','SaveFormat','Array','SampleTime','1', ...
    'MaxDataPoints','inf','Position',[470 200 550 230]);
add_block('simulink/Sinks/To Workspace',[s2 '/LogRes'], ...
    'VariableName','s2_res','SaveFormat','Array','SampleTime','1', ...
    'MaxDataPoints','inf','Position',[470 100 550 130]);

% Qstate output = q[k] (no direct feedthrough -> no algebraic loop with MPC)
add_line(s2,'Qstate/1','QueueStep/1');
add_line(s2,'In1/1','QueueStep/2');          % demand
add_line(s2,'In2/1','QueueStep/3');          % active branch (0 = clearance)
add_line(s2,'QueueStep/1','Qstate/1');       % qNext -> unit delay
add_line(s2,'QueueStep/2','LogRes/1');
add_line(s2,'Qstate/1','Out1/1');            % q -> MPC
add_line(s2,'Qstate/1','Out2/1');            % q -> validation
add_line(s2,'Qstate/1','LogQ/1');

%% ---------- model hygiene & save ----------
set_param(modelName, ...
    'UnconnectedInputMsg','none','UnconnectedOutputMsg','none', ...
    'UnconnectedLineMsg','none','ReturnWorkspaceOutputs','on');
save_system(modelName);

fprintf('\nS2 built: 01_Traffic_Demand and 02_Traffic_Queue_Plant populated.\n');
fprintf('Status: IMPLEMENTED - NOT PASS until test_SITRA_S2 passes.\n');
fprintf('Next: run test_SITRA_S2\n');

%% ---------- local helpers ----------
function clearSubsystem(sys)
    blks = find_system(sys,'SearchDepth',1,'Type','Block');
    for i = 1:numel(blks)
        if strcmp(blks{i},sys), continue; end
        bt = get_param(blks{i},'BlockType');
        if ~any(strcmp(bt,{'Inport','Outport'}))
            delete_block(blks{i});
        end
    end
    lns = find_system(sys,'SearchDepth',1,'FindAll','on','Type','Line');
    for i = 1:numel(lns)
        if ishandle(lns(i)), delete_line(lns(i)); end
    end
end

function addMatlabFunction(sys,name,code,pos)
    p = [sys '/' name];
    add_block('simulink/User-Defined Functions/MATLAB Function',p,'Position',pos);
    rt = sfroot;
    ch = rt.find('-isa','Stateflow.EMChart','Path',p);
    ch.Script = code;
end
