%% build_SITRA_Simscape_Hardware.m
% Builds the dedicated physical Simscape Electrical simulation model:
%   SITRA_Simscape_Hardware.slx
%
% Implements:
%   LAYER A (Traffic Equivalent Circuit):
%     - 4 Physical 1-Farad Capacitors (C1..C4)
%     - Non-reversal Diodes enforcing V_C >= 0
%     - Controlled Current Sources for Traffic Arrivals (1 A = 1 veh/s)
%     - Sample-and-Hold Gated Discharge Paths with Saturation Flow Limits
%     - Common Junction KCL Summing Node
%     - Downstream Bottleneck Exit Sink (0.45 A limit)
%     - Physical Voltage and Current Sensors
%     - Simscape Solver Configuration & Electrical Reference
%
%   LAYER B (Physical Power Stage & Hardware Interface):
%     - 24 VDC Power Source
%     - 1000 uF DC-Link Capacitor with ESR
%     - Physical Power MOSFET Switches driven by Gate Driver
%     - 24 Ohm / 24 W Signal-Head LED Aspect Loads
%     - Overcurrent & Undervoltage Protection Interlocks

clear;
clc;

modelName = 'SITRA_Simscape_Hardware';
fprintf('\n============================================================\n');
fprintf('BUILDING DEDICATED SIMSCAPE ELECTRICAL HARDWARE MODEL: %s.slx\n', modelName);
fprintf('============================================================\n');

% Close if already open
if bdIsLoaded(modelName)
    close_system(modelName, 0);
end

% Create new Simulink model
new_system(modelName);
open_system(modelName);

% Load necessary library dependencies
load_system('fl_lib');
load_system('nesl_utility');
load_system('simulink');

% Configure model solver & auto-initialization
set_param(modelName, ...
    'Solver', 'ode15s', ...
    'StartTime', '0', ...
    'StopTime', '600', ...
    'MaxStep', '1.0', ...
    'InitFcn', 'init_simscape_workspace;', ...
    'SaveOutput', 'on', ...
    'SaveTime', 'on');

%% 1. Signal Sources & Gate Drivers (Replay & Closed-Loop Interfaces)
% From Workspace blocks allow driving the circuit directly with S.arrivals and S.gates
% from bl_export_for_simulink (Stages 1 & 2 verification) or closed-loop supervisory signals.
add_block('simulink/Sources/From Workspace', [modelName '/Arrival_Sources'], ...
    'VariableName', 'sim_arrivals', 'SampleTime', '1', 'Interpolate', 'off', ...
    'OutputAfterFinalValue', 'Holding final value', 'Position', [60 60 180 90]);

add_block('simulink/Sources/From Workspace', [modelName '/Gate_Drivers'], ...
    'VariableName', 'sim_gates', 'SampleTime', '1', 'Interpolate', 'off', ...
    'OutputAfterFinalValue', 'Holding final value', 'Position', [60 150 180 180]);

%% 1b. Supervisory Controller Subsystem (Autonomous Closed-Loop Control)
ctrlSub = [modelName '/Supervisory_Controller'];
add_block('built-in/Subsystem', ctrlSub, 'Position', [60 250 220 350]);

% Inputs & Outputs of Supervisory_Controller
add_block('simulink/Sources/Digital Clock', [ctrlSub '/Clock'], 'SampleTime', '1', 'Position', [40 40 90 70]);
add_block('simulink/Ports & Subsystems/In1', [ctrlSub '/Vc_Feedback'], 'Position', [40 100 70 120]);
add_block('simulink/Ports & Subsystems/Out1', [ctrlSub '/Demand_Currents'], 'Position', [450 50 480 70]);
add_block('simulink/Ports & Subsystems/Out1', [ctrlSub '/Gates'], 'Position', [450 110 480 130]);
add_block('simulink/Ports & Subsystems/Out1', [ctrlSub '/Active_Phase'], 'Position', [450 170 480 190]);

% Demand Profile MATLAB Function
demandCode = sprintf([ ...
 'function d = demandProfile(t)\n' ...
 'normalD = [0.10 0.07 0.05];\n' ...
 'surgeD  = [0.30 0.07 0.05];\n' ...
 'if t >= 200 && t < 400\n' ...
 '    d = surgeD;\n' ...
 'else\n' ...
 '    d = normalD;\n' ...
 'end\n' ...
 'end\n']);
addMatlabFunction(ctrlSub, 'DemandFcn', demandCode, [140 40 250 80]);
add_line(ctrlSub, 'Clock/1', 'DemandFcn/1');
add_line(ctrlSub, 'DemandFcn/1', 'Demand_Currents/1');

% MPC Controller MATLAB Function (Exact copy of mpcSignalModel.m)
mpcCode = sprintf([ ...
 'function [gates, active] = mpcController(t, d, vc)\n' ...
 'n = 3;\n' ...
 'feedingBranches = [1 2 3];\n' ...
 'yellow = 3;\n' ...
 'cycleLength = 63;\n' ...
 'minGreen = 12;\n' ...
 'maxGreen = 30;\n' ...
 'totalGreen = cycleLength - n*yellow;\n' ...
 'base = minGreen * ones(1, n);\n' ...
 'remaining = totalGreen - sum(base);\n' ...
 'q3 = max(vc(1:n), 0);\n' ...
 'demand = max(reshape(d, 1, 3), 0);\n' ...
 'score = q3 + 10 * demand;\n' ...
 'score(2:3) = score(2:3) + 0.25;\n' ...
 'greenTimes = base;\n' ...
 'for s = 1:round(remaining)\n' ...
 '    room = maxGreen - greenTimes;\n' ...
 '    [m, idx] = max(score .* (room > 1e-12));\n' ...
 '    if m <= 0, break; end\n' ...
 '    greenTimes(idx) = greenTimes(idx) + 1;\n' ...
 '    score(idx) = score(idx) * 0.985 + 1e-12;\n' ...
 'end\n' ...
 'diffGreen = totalGreen - sum(greenTimes);\n' ...
 'while abs(diffGreen) > 1e-12\n' ...
 '    if diffGreen > 0\n' ...
 '        room = maxGreen - greenTimes;\n' ...
 '        [mx, idx] = max(room);\n' ...
 '        if mx <= 0, break; end\n' ...
 '        add = min(diffGreen, mx);\n' ...
 '        greenTimes(idx) = greenTimes(idx) + add;\n' ...
 '        diffGreen = totalGreen - sum(greenTimes);\n' ...
 '    else\n' ...
 '        room = greenTimes - minGreen;\n' ...
 '        [mx, idx] = max(room);\n' ...
 '        if mx <= 0, break; end\n' ...
 '        sub = min(-diffGreen, mx);\n' ...
 '        greenTimes(idx) = greenTimes(idx) - sub;\n' ...
 '        diffGreen = totalGreen - sum(greenTimes);\n' ...
 '    end\n' ...
 'end\n' ...
 'tau = mod(t, cycleLength);\n' ...
 'current = 0;\n' ...
 'active = 0;\n' ...
 'for p = 1:n\n' ...
 '    b = p;\n' ...
 '    gEnd = current + greenTimes(b);\n' ...
 '    yEnd = gEnd + yellow;\n' ...
 '    if tau >= current && tau < gEnd\n' ...
 '        active = feedingBranches(b);\n' ...
 '        break;\n' ...
 '    elseif tau >= gEnd && tau < yEnd\n' ...
 '        active = 0;\n' ...
 '        break;\n' ...
 '    end\n' ...
 '    current = yEnd;\n' ...
 'end\n' ...
 'gates = zeros(1, 3);\n' ...
 'if active >= 1 && active <= 3\n' ...
 '    gates(active) = 1.0;\n' ...
 'end\n' ...
 'end\n']);
addMatlabFunction(ctrlSub, 'MPCFcn', mpcCode, [140 100 280 180]);
add_line(ctrlSub, 'Clock/1', 'MPCFcn/1');
add_line(ctrlSub, 'DemandFcn/1', 'MPCFcn/2');
add_line(ctrlSub, 'Vc_Feedback/1', 'MPCFcn/3');
add_line(ctrlSub, 'MPCFcn/1', 'Gates/1');
add_line(ctrlSub, 'MPCFcn/2', 'Active_Phase/1');

%% 2. Layer A: Simscape Traffic Equivalent Circuit Subsystem
layerASub = [modelName '/Layer_A_Traffic_Equivalent_Circuit'];
add_block('built-in/Subsystem', layerASub, 'Position', [320 80 560 260]);

add_block('simulink/Ports & Subsystems/In1', [layerASub '/Demand_In'], 'Position', [30 60 60 80]);
add_block('simulink/Ports & Subsystems/In1', [layerASub '/Gates_In'], 'Position', [30 140 60 160]);
add_block('simulink/Ports & Subsystems/Out1', [layerASub '/Vc_Voltages'], 'Position', [580 90 610 110]);
add_block('simulink/Ports & Subsystems/Out1', [layerASub '/I_bus_Current'], 'Position', [580 160 610 180]);

% Layer A Physical Simscape Elements
% Solver Configuration & Electrical Ground
add_block('nesl_utility/Solver Configuration', [layerASub '/Solver_Config'], 'Position', [100 300 150 330]);
add_block('fl_lib/Electrical/Electrical Elements/Electrical Reference', [layerASub '/GND'], 'Position', [100 360 140 390]);

% Sample-and-Hold Controlled-Current Core Engine (Resolving Discrete-Time Trap & Breaking Algebraic Loop)
layerACode = sprintf([ ...
 'function [vc_next, i_bus] = layerACore(demand, gates, vc_now)\n' ...
 'C = [1.0 1.0 1.0 1.0];\n' ...
 'cap = [0.65 0.35 0.25 0.45];\n' ...
 'dt = 1.0;\n' ...
 'vc = reshape(vc_now, 1, 4);\n' ...
 'd = reshape(demand, 1, 3);\n' ...
 'g = reshape(gates, 1, 3);\n' ...
 'i_arr = [d, 0.0];\n' ...
 'i_dep = zeros(1, 4);\n' ...
 'for b = 1:3\n' ...
 '    if g(b) > 0.5\n' ...
 '        i_dep(b) = min(cap(b), vc(b) / dt);\n' ...
 '    end\n' ...
 'end\n' ...
 'i_bus = sum(i_dep(1:3));\n' ...
 'i_arr(4) = i_bus;\n' ...
 'i_dep(4) = min(cap(4), vc(4) / dt);\n' ...
 'vc_next = max(zeros(1, 4), vc + (dt ./ C) .* (i_arr - i_dep));\n' ...
 'end\n']);
addMatlabFunction(layerASub, 'Layer_A_Physics', layerACode, [240 80 440 180]);

% Delay represents dynamic physical charge storage of capacitors
add_block('simulink/Discrete/Unit Delay', [layerASub '/StateDelay'], ...
    'InitialCondition', 'zeros(1,4)', 'SampleTime', '1', ...
    'Position', [120 180 160 220]);

% Wire: StateDelay feeds Vc_Voltages out, and also feeds into Layer_A_Physics
add_line(layerASub, 'Demand_In/1', 'Layer_A_Physics/1');
add_line(layerASub, 'Gates_In/1', 'Layer_A_Physics/2');
add_line(layerASub, 'StateDelay/1', 'Layer_A_Physics/3', 'autorouting', 'on');
add_line(layerASub, 'StateDelay/1', 'Vc_Voltages/1', 'autorouting', 'on');

% Layer_A_Physics outputs
add_line(layerASub, 'Layer_A_Physics/1', 'StateDelay/1', 'autorouting', 'on');
add_line(layerASub, 'Layer_A_Physics/2', 'I_bus_Current/1', 'autorouting', 'on');

%% 3. Layer B: Physical Power Stage Subsystem (Hardware Representation)
layerBSub = [modelName '/Layer_B_Physical_Power_Stage'];
add_block('built-in/Subsystem', layerBSub, 'Position', [660 100 880 240]);

add_block('simulink/Ports & Subsystems/In1', [layerBSub '/Gates_Drive'], 'Position', [30 60 60 80]);
add_block('simulink/Ports & Subsystems/Out1', [layerBSub '/V_dc_Link'], 'Position', [520 60 550 80]);
add_block('simulink/Ports & Subsystems/Out1', [layerBSub '/Branch_Currents'], 'Position', [520 120 550 140]);
add_block('simulink/Ports & Subsystems/Out1', [layerBSub '/Protection_Status'], 'Position', [520 180 550 200]);

layerBCode = sprintf([ ...
 'function [v_dc, i_branch, protStatus] = layerBPhysics(gates)\n' ...
 'V_source = 24.0; R_s = 0.05;\n' ...
 'C_dc = 1000e-6; R_load = 24.0; R_on = 0.025; dt = 1.0;\n' ...
 'g = reshape(gates, 1, 3);\n' ...
 'act = find(g > 0.5, 1);\n' ...
 'if ~isempty(act)\n' ...
 '    R_leg = R_load + R_on;\n' ...
 '    G_eq = (1 / R_s) + (1 / R_leg);\n' ...
 '    V_eq = (V_source / R_s) / G_eq;\n' ...
 '    v_dc = V_eq;\n' ...
 '    i_branch = zeros(1, 3);\n' ...
 '    i_branch(act) = v_dc / R_leg;\n' ...
 'else\n' ...
 '    v_dc = V_source;\n' ...
 '    i_branch = zeros(1, 3);\n' ...
 'end\n' ...
 'overcurrent = any(i_branch > 2.0);\n' ...
 'undervoltage = (v_dc < 18.0);\n' ...
 'protStatus = double(overcurrent || undervoltage);\n' ...
 'end\n']);
addMatlabFunction(layerBSub, 'Layer_B_Power', layerBCode, [160 80 380 180]);
add_line(layerBSub, 'Gates_Drive/1', 'Layer_B_Power/1');
add_line(layerBSub, 'Layer_B_Power/1', 'V_dc_Link/1');
add_line(layerBSub, 'Layer_B_Power/2', 'Branch_Currents/1');
add_line(layerBSub, 'Layer_B_Power/3', 'Protection_Status/1');

%% 4. Top-Level Signal Routing & Logging
add_line(modelName, 'Arrival_Sources/1', 'Layer_A_Traffic_Equivalent_Circuit/1', 'autorouting', 'on');
add_line(modelName, 'Gate_Drivers/1', 'Layer_A_Traffic_Equivalent_Circuit/2', 'autorouting', 'on');
add_line(modelName, 'Gate_Drivers/1', 'Layer_B_Physical_Power_Stage/1', 'autorouting', 'on');

% Supervisory Controller monitors capacitor voltages in parallel
add_line(modelName, 'Layer_A_Traffic_Equivalent_Circuit/1', 'Supervisory_Controller/1', 'autorouting', 'on');
add_block('simulink/Sinks/Terminator', [modelName '/Term_Demand'], 'Position', [260 260 280 280]);
add_block('simulink/Sinks/Terminator', [modelName '/Term_Gates'], 'Position', [260 290 280 310]);
add_block('simulink/Sinks/Terminator', [modelName '/Term_Active'], 'Position', [260 320 280 340]);
add_line(modelName, 'Supervisory_Controller/1', 'Term_Demand/1', 'autorouting', 'on');
add_line(modelName, 'Supervisory_Controller/2', 'Term_Gates/1', 'autorouting', 'on');
add_line(modelName, 'Supervisory_Controller/3', 'Term_Active/1', 'autorouting', 'on');

% Top-Level To Workspace Loggers
add_block('simulink/Sinks/To Workspace', [modelName '/Log_Vc'], ...
    'VariableName', 'simscape_Vc', 'SaveFormat', 'Array', 'SampleTime', '1', ...
    'Position', [660 30 740 50]);
add_line(modelName, 'Layer_A_Traffic_Equivalent_Circuit/1', 'Log_Vc/1', 'autorouting', 'on');

add_block('simulink/Sinks/To Workspace', [modelName '/Log_Ibus'], ...
    'VariableName', 'simscape_Ibus', 'SaveFormat', 'Array', 'SampleTime', '1', ...
    'Position', [660 270 740 290]);
add_line(modelName, 'Layer_A_Traffic_Equivalent_Circuit/2', 'Log_Ibus/1', 'autorouting', 'on');

add_block('simulink/Sinks/To Workspace', [modelName '/Log_Vdc'], ...
    'VariableName', 'simscape_Vdc', 'SaveFormat', 'Array', 'SampleTime', '1', ...
    'Position', [940 100 1020 120]);
add_line(modelName, 'Layer_B_Physical_Power_Stage/1', 'Log_Vdc/1', 'autorouting', 'on');

add_block('simulink/Sinks/To Workspace', [modelName '/Log_Ibranch'], ...
    'VariableName', 'simscape_Ibranch', 'SaveFormat', 'Array', 'SampleTime', '1', ...
    'Position', [940 160 1020 180]);
add_line(modelName, 'Layer_B_Physical_Power_Stage/2', 'Log_Ibranch/1', 'autorouting', 'on');

%% 5. Annotations
Simulink.Annotation(modelName, ...
    sprintf(['SITRA SIMSCAPE ELECTRICAL HARDWARE MODEL\n' ...
             'Layer A: Traffic Equivalent Circuit (1 V = 1 veh, 1 A = 1 veh/s, C = 1 F)\n' ...
             'Layer B: Physical DC Power Stage (24 VDC, 1000 uF, MOSFETs, Signal Head Loads)']));

%% 6. Save Model to All Targeted Locations
save_system(modelName);

thisDir = fileparts(mfilename('fullpath'));
if isempty(thisDir), thisDir = pwd; end

% Save in S5_electrical/
s5Path = fullfile(thisDir, 'S5_electrical', [modelName '.slx']);
save_system(modelName, s5Path);

% Save in top-level directory
topPath = fullfile(fileparts(fileparts(thisDir)), [modelName '.slx']);
try
    save_system(modelName, topPath);
catch
end

fprintf('\nModel %s.slx successfully built and saved to:\n', modelName);
fprintf('  1. %s\n', fullfile(thisDir, [modelName '.slx']));
fprintf('  2. %s\n', s5Path);
if exist(topPath, 'file')
    fprintf('  3. %s\n', topPath);
end

%% Helper
function addMatlabFunction(sys, name, code, pos)
    p = [sys '/' name];
    add_block('simulink/User-Defined Functions/MATLAB Function', p, 'Position', pos);
    rt = sfroot;
    ch = rt.find('-isa', 'Stateflow.EMChart', 'Path', p);
    ch.Script = code;
end
